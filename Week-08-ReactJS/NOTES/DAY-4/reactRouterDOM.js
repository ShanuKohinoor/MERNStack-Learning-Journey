// It is a library used to create multi-page like experience in a single page app(SPA).

//        Eg:-
//          Home -->   /
//          About Page --> /about
//          Contact Page --> /contact

                     // But React still in one page,but Router changes components.

// It enables navigation between pages in React without reloading the page.



// React Router works on this rule:-
//         Match URL --> Render component

//  when URL changes ---> component changes(but without page reloads)



//    Eg:- 
//           URL = '/about'

//           React checks routes
//                 |
//                 |
//                 v
//           Find matching path
//                 |
//                 |
//                 v
//           Renders that component