//                                  Folder Architecture
//                                  -------------------



// It means how we organize files and folders in a React project.



// Eg:-

// src/
// │
// ├── components/       --> reusable small UI parts (Button,Navbar, Card)
// ├── pages/            --> full pages (Home, About)/full screen of app
// ├── hooks/            --> custom hooks
// ├── context/          --> Global state management(AuthContext,ThemeContext)
// ├── services/         --> API calls(backend communication)
// ├── utils/            --> helper functions(formatDate(),validateEmail())
// ├── assets/           --> images, icons
// ├── App.jsx
// └── main.jsx